#!/usr/bin/env python3
"""
Builds the relay web page (web/relay.html + the QR code library) and embeds it in both relays:
  server/octopus_relay.py   (Python home-server relay)
  worker/src/index.js       (Cloudflare Worker relay)

Run after editing web/relay.html:   python3 tools/build_pages.py
The page is embedded (rather than served from a file) so each relay stays a single file.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "PAGE (generated by tools/build_pages.py from web/relay.html - edit that file, not this)"


def shrink_js(src: str) -> str:
    """Light, safe size reduction: drops whole-line // comments, leading indentation and blank lines."""
    out = []
    for line in src.splitlines():
        s = line.strip()
        if not s or (s.startswith("//") and "://" not in s):
            continue
        out.append(s)
    return "\n".join(out)


def build() -> str:
    html = (ROOT / "web/relay.html").read_text()
    lib = (ROOT / "web/vendor/qrcode.js").read_text()
    header = lib.splitlines()[0]   # keep the licence line
    html = html.replace("/*QRCODE_LIB*/", header + "\n" + shrink_js(lib))
    return html


def embed(path: pathlib.Path, line: str, comment: str):
    text = path.read_text()
    pattern = re.compile(rf"^{re.escape(comment)} BEGIN {re.escape(BEGIN)}\n.*?^{re.escape(comment)} END PAGE\n", re.S | re.M)
    block = f"{comment} BEGIN {BEGIN}\n{line}\n{comment} END PAGE\n"
    if not pattern.search(text):
        raise SystemExit(f"Markers not found in {path}")
    path.write_text(pattern.sub(lambda _: block, text))
    print(f"Updated {path.relative_to(ROOT)}")


if __name__ == "__main__":
    page = build()
    literal = json.dumps(page)   # a valid string literal in both Python and JavaScript
    embed(ROOT / "server/octopus_relay.py", f"PAGE = {literal}", "#")
    embed(ROOT / "worker/src/index.js", f"const PAGE = {literal};", "//")
    print(f"Page size: {len(page) // 1024} KB")
